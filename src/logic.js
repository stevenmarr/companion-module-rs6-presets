function variableValues(state) {
  const v = {
    last_preset_number: state && state.lastRecalled ? state.lastRecalled.number : '',
    last_preset_name: state && state.lastRecalled ? state.lastRecalled.name : '',
    program_presets: state && state.programPresets ? state.programPresets.join(',') : '',
    // what TAKE / CUT will act on (app 0.3.1 transitionTargets; the plain selection on older apps)
    selection: selectionKeys(state).join(','),
    auto_take: state && state.autoTake ? 'ON' : 'OFF',
    device_connected: state ? String(!!state.connected) : 'false',
    app_version: (state && state.appVersion) || '',
    app_api_version: state && state.apiVersion ? String(state.apiVersion) : '',
    show_name: (state && state.show && state.show.name) || '',
    tile_count: String(tileCount(state)),
  };
  // The preset's name, or its number when it has none (the recall buttons show this variable).
  const byNum = new Map(((state && state.presets) || []).map((p) => [Number(p.number), p]));
  for (const n of presetSlots(state)) { const p = byNum.get(n); v[`preset_${n}_name`] = p ? String(p.name || '').trim() || String(n) : `${n} (empty)`; }
  const lv = live(state);
  v.live_mode = lv ? lv.mode || 'off' : 'off';
  const lm = (lv && lv.lastMaster) || {};
  v.master_pgm_number = memNum(lm.program); v.master_pgm_name = memName(lm.program);
  v.master_pvw_number = memNum(lm.preview); v.master_pvw_name = memName(lm.preview);
  for (const d of (state && state.destinations) || []) {
    v[`${d.key}_pgm_memory_number`] = memNum(d.programMemory); v[`${d.key}_pgm_memory_name`] = memName(d.programMemory);
    v[`${d.key}_pvw_memory_number`] = memNum(d.previewMemory); v[`${d.key}_pvw_memory_name`] = memName(d.previewMemory);
    v[`${d.key}_pgm_layer1`] = d.programLayer1 || '';
  }
  for (const i of liveInputs(state)) v[`input_${i.number}_label`] = i.label || '';
  for (const type of ['screen', 'master', 'multiviewer']) {
    for (const i of memItems(state, type)) if (i.label) v[`${type === 'multiviewer' ? 'mv' : type}_mem_${i.slot}_name`] = i.label;
  }
  for (const n of presetSlots(state)) { const p = byNum.get(n); v[`preset_${n}_summary`] = p ? presetSummary(p) : ''; }
  for (const g of backupGroups(state)) {
    v[`backup_group_${g.group}_name`] = groupLabel(g);
    v[`bk_grp_${g.group}_state`] = backupStateText(g);
    v[`bk_grp_${g.group}_members`] = (g.members || []).map((m) => m.label).filter(Boolean).join(' · ');
  }
  const bk = backupLive(state);
  for (const b of bk.inputs || []) {
    v[`bk_in_${b.number}_name`] = b.label || `IN ${b.number}`;
    v[`bk_in_${b.number}_src1`] = backupSourceName(state, (b.slots || {})[1] || (b.slots || {})['1']);
    v[`bk_in_${b.number}_src2`] = backupSourceName(state, (b.slots || {})[2] || (b.slots || {})['2']);
    v[`bk_in_${b.number}_state`] = backupStateText(b);
  }
  for (const b of bk.backgrounds || []) {
    const k = bgKey(b);
    v[`bk_bg_${k}_name`] = `${b.screen} BG ${b.set}`;
    v[`bk_bg_${k}_src1`] = backupSourceName(state, (b.slots || {})[1] || (b.slots || {})['1']);
    v[`bk_bg_${k}_src2`] = backupSourceName(state, (b.slots || {})[2] || (b.slots || {})['2']);
    v[`bk_bg_${k}_state`] = backupStateText(b);
  }
  v.memories_imported = (state && state.memories && state.memories.import && state.memories.import.at) || '';
  return v;
}

function presetSignature(state) {
  return JSON.stringify({
    p: ((state && state.presets) || []).map((p) => [p.number, p.name, presetSummary(p)]),
    m: ['screen', 'master', 'multiviewer'].map((t) => memItems(state, t).map((i) => [i.slot, i.label])),
    v: ((state && state.multiviewers) || []).map((x) => [x.key, x.label]),
    d: ((state && state.destinations) || []).map((d) => [d.key, d.label]),
    i: liveInputs(state).map((i) => [i.number, i.label]),
    g: backupGroups(state).map((g) => [g.group, g.label, (g.members || []).length]),
    t: tileCount(state), api: state && state.apiVersion,
    a: ((live(state) && live(state).audio) || { inputs: [], outputs: [] }),
    b: (backupLive(state).inputs || []).map((x) => x.number),
    bg: (backupLive(state).backgrounds || []).map((x) => [x.screen, x.set]),
  }, (k, val) => (k === 'mute' ? undefined : val)); // structure only, not mute values
}

// `label` is this connection's label in Companion (variables are $(<label>:name)); the default label is
// the manifest shortname, rs6presets, but users can rename the connection.
function buttonPresets(state, label = 'rs6presets') { return relabel(buildPresets(state), label); }
// preset texts use $(rs6presets:...); point them at this connection's label
function relabel(out, label = 'rs6presets') {
  if (label && label !== 'rs6presets') {
    for (const b of Object.values(out)) if (b.style && typeof b.style.text === 'string') b.style.text = b.style.text.split('$(rs6presets:').join(`$(${label}:`);
  }
  return out;
}

function buildPresets(state) {
  const out = {};
  // 0.5.0: one button per TILE (1..tile count), in pages of 24 like the app's pager / a Stream Deck XL page.
  // Buttons follow the tile: after a move or swap in the app they show / recall / tally what is there now.
  const byNum = new Map(((state && state.presets) || []).map((p) => [Number(p.number), p]));
  for (const n of presetSlots(state)) {
    const p = byNum.get(n); const lo = Math.floor((n - 1) / 24) * 24 + 1;
    out[`preset_${n}`] = {
      type: 'button', category: `Preset tiles ${lo}-${lo + 23}`, name: p ? `${n} ${p.name}` : `${n} (empty tile)`,
      // Name only (live through the variable; it falls back to the number). size auto wraps on spaces.
      style: look('preset', `$(rs6presets:preset_${n}_name)`),
      steps: [{ down: [{ actionId: 'recall_preset', options: { preset: n } }], up: [] }],
      feedbacks: [
        { feedbackId: 'preset_pvw', options: { preset: n, partial: false }, style: lit('preset_pvw', COLORS.green) },
        { feedbackId: 'preset_pgm', options: { preset: n, partial: false }, style: lit('preset_pgm', COLORS.red) },
      ],
    };
  }
  for (const i of memItems(state, 'master')) {
    out[`master_mem_${i.slot}`] = {
      type: 'button', category: 'Master memories', name: `Load Master ${i.slot} ${i.label || ''} to PVW`,
      style: look('master', i.label ? `$(rs6presets:master_mem_${i.slot}_name)` : `MASTER ${i.slot}`),
      steps: [{ down: [{ actionId: 'load_master_memory', options: { memory: i.slot, target: 'preview' } }], up: [] }],
      feedbacks: [
        { feedbackId: 'master_memory', options: { side: 'pvw', memory: i.slot }, style: lit('master_pvw', COLORS.green) },
        { feedbackId: 'master_memory', options: { side: 'pgm', memory: i.slot }, style: lit('master_pgm', COLORS.red) },
      ],
    };
  }
  out.refresh_memories = { type: 'button', category: 'Status', name: 'Re-import memories from the RS6', style: look('utility', 'REFRESH\\nMEMORY'), steps: [{ down: [{ actionId: 'refresh_memories', options: {} }], up: [] }], feedbacks: [] };
  out.logo = { type: 'button', category: 'Status', name: 'Performance Video logo', style: { text: '', size: TEXT_SIZE, color: COLORS.white, bgcolor: COLORS.black, png64: LOGO_PNG64, show_topbar: false }, steps: [{ down: [], up: [] }], feedbacks: [] };
  for (const d of (state && state.destinations) || []) {
    out[`dest_${d.key}`] = {
      type: 'button', category: 'Destinations', name: `Toggle ${d.key} ${d.label}`,
      style: look('dest', `${d.key}\\n${d.label}`),
      steps: [{ down: [{ actionId: 'toggle_destination', options: { dest: d.key } }], up: [] }],
      feedbacks: [{ feedbackId: 'dest_selected', options: { dest: d.key }, style: lit('dest_sel', COLORS.amber, COLORS.black) }],
    };
  }
  out.take = { type: 'button', category: 'Transitions', name: 'TAKE', style: look('take', 'TAKE\\n$(rs6presets:selection)', COLORS.white, COLORS.red), steps: [{ down: [{ actionId: 'take', options: {} }], up: [] }], feedbacks: [] };
  out.cut = { type: 'button', category: 'Transitions', name: 'CUT', style: look('cut', 'CUT\\n$(rs6presets:selection)', COLORS.white, COLORS.darkred), steps: [{ down: [{ actionId: 'cut', options: {} }], up: [] }], feedbacks: [] };
  out.auto_take = {
    type: 'button', category: 'Transitions', name: 'Auto take toggle',
    style: look('auto', 'AUTO\\nTAKE\\n$(rs6presets:auto_take)'),
    steps: [{ down: [{ actionId: 'auto_take', options: { mode: 'toggle' } }], up: [] }],
    feedbacks: [{ feedbackId: 'auto_take_on', options: {}, style: lit('auto_sel', COLORS.amber, COLORS.black) }],
  };
  // ---- live device presets ----
  for (const i of liveInputs(state)) {
    const lbl = `$(rs6presets:input_${i.number}_label)`;
    out[`input_tally_${i.number}`] = {
      type: 'button', category: 'Input tally', name: `Tally IN ${i.number} ${i.label || ''}`,
      style: look('tally', `IN ${i.number}\\n${lbl}`),
      steps: [{ down: [], up: [] }],
      feedbacks: [
        { feedbackId: 'input_pvw', options: { input: i.number, dest: 'any' }, style: lit('tally_pvw', COLORS.green) },
        { feedbackId: 'input_pgm', options: { input: i.number, dest: 'any' }, style: lit('tally_pgm', COLORS.red) },
        { feedbackId: 'input_problem', options: { input: i.number, what: 'either' }, style: { color: COLORS.yellow } },
      ],
    };
    out[`input_freeze_${i.number}`] = {
      type: 'button', category: 'Input freeze', name: `Freeze IN ${i.number} ${i.label || ''}`,
      style: look('freeze', `FRZ ${i.number}\\n${lbl}`),
      steps: [{ down: [{ actionId: 'input_freeze', options: { input: i.number, mode: 'toggle' } }], up: [] }],
      feedbacks: [{ feedbackId: 'input_frozen', options: { input: i.number }, style: lit('freeze_frozen', COLORS.blue) }],
    };
  }
  const bk = backupLive(state);
  const slotWord = (slot) => (slot === 'NONE' ? 'PRIMARY' : `BKP ${slot}`);
  // Line 1 is the source this backup protects. Line 2 is the slot and, for a backup slot, the
  // source it switches to (LIVE_n resolved to that input's label). The last line is the live
  // state (PRIMARY / BKP n, plus AUTO). size auto shrinks so a long name does not clip.
  const bkFace = (nameId, stateId, slot, srcId) => {
    const slotLine = srcId && slot !== 'NONE' ? `${slotWord(slot)} $(rs6presets:${srcId})` : slotWord(slot);
    return `$(rs6presets:${nameId})\n${slotLine}\n$(rs6presets:${stateId})`;
  };
  for (const b of bk.inputs || []) {
    for (const slot of ['NONE', '1', '2']) {
      out[`input_backup_${b.number}_${slot}`] = {
        type: 'button', category: 'Backups', name: `IN ${b.number} ${b.label || ''} ${slotWord(slot)}`,
        style: look('backup', bkFace(`bk_in_${b.number}_name`, `bk_in_${b.number}_state`, slot, `bk_in_${b.number}_src${slot}`)),
        steps: [{ down: [{ actionId: 'backup_trigger', options: { kind: 'input', id: String(b.number), slot } }], up: [] }],
        feedbacks: [{ feedbackId: 'backup_active', options: { kind: 'input', id: String(b.number), slot }, style: lit('backup_sel', COLORS.amber, COLORS.black) }],
      };
    }
  }
  for (const b of bk.backgrounds || []) {
    const id = `${b.screen}/${b.set}`; const k = bgKey(b);
    for (const slot of ['NONE', '1', '2']) {
      out[`bg_backup_${k}_${slot}`] = {
        type: 'button', category: 'Background backups', name: `${id} ${slotWord(slot)}`,
        style: look('backup', bkFace(`bk_bg_${k}_name`, `bk_bg_${k}_state`, slot, `bk_bg_${k}_src${slot}`)),
        steps: [{ down: [{ actionId: 'backup_trigger', options: { kind: 'bg', id, slot } }], up: [] }],
        feedbacks: [{ feedbackId: 'backup_active', options: { kind: 'bg', id, slot }, style: lit('backup_sel', COLORS.amber, COLORS.black) }],
      };
    }
  }
  for (const g of bk.groups || []) {
    for (const slot of ['NONE', '1', '2']) {
      out[`group_backup_${g.group}_${slot}`] = {
        type: 'button', category: 'Backup groups', name: `Group ${g.group} ${groupLabel(g)} ${slotWord(slot)}`,
        style: look('backup', `${bkFace(`backup_group_${g.group}_name`, `bk_grp_${g.group}_state`, slot)}\n$(rs6presets:bk_grp_${g.group}_members)`),
        steps: [{ down: [{ actionId: 'backup_trigger', options: { kind: 'group', id: String(g.group), slot } }], up: [] }],
        feedbacks: [{ feedbackId: 'backup_active', options: { kind: 'group', id: String(g.group), slot }, style: lit('backup_sel', COLORS.amber, COLORS.black) }],
      };
    }
  }
  const au = (live(state) && live(state).audio) || { inputs: [], outputs: [] };
  for (const [dir, key, short] of [['inputs', 'input', 'IN'], ['outputs', 'output', 'OUT']]) {
    for (const row of au[dir] || []) {
      for (const c of row.channels) {
        out[`audio_${dir}_${row[key]}_${c.channel}`] = {
          type: 'button', category: `Audio ${dir} mute`, name: `Mute audio ${key} ${row[key]} ch ${c.channel}`,
          style: look('audio', `${short} ${row[key]}\\nCH ${c.channel}\\nMUTE`),
          steps: [{ down: [{ actionId: 'audio_mute', options: { dir, id: row[key], channel: c.channel, mode: 'toggle' } }], up: [] }],
          feedbacks: [{ feedbackId: 'audio_muted', options: { dir, id: row[key], channel: c.channel }, style: lit('audio_muted', COLORS.red) }],
        };
      }
    }
  }
  out.master_status = { type: 'button', category: 'Status', name: 'Last Master memory (PGM)', style: look('status', 'MASTER\\n$(rs6presets:master_pgm_number)\\n$(rs6presets:master_pgm_name)', COLORS.lightred, COLORS.black), steps: [{ down: [], up: [] }], feedbacks: [] };
  out.last = { type: 'button', category: 'Status', name: 'Last recalled preset', style: look('status', 'PVW\\n$(rs6presets:last_preset_number)\\n$(rs6presets:last_preset_name)', COLORS.lightgreen, COLORS.black), steps: [{ down: [], up: [] }], feedbacks: [] };
  return out;
}

