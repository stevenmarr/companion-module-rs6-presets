// AWJ backup slot values (LIVE_9, STILL_1, NATIVE_2) shown as the source they switch to.
function backupSourceName(state, token) {
  const raw = token == null ? '' : String(token);
  if (!raw || raw === 'NONE') return '';
  let m = /^LIVE_(\d+)$/.exec(raw);
  if (m) { const i = findInput(state, m[1]); return (i && i.label) || `IN ${m[1]}`; }
  m = /^STILL_(\d+)$/.exec(raw);
  if (m) return `Still ${m[1]}`;
  m = /^NATIVE_(\d+)$/.exec(raw);
  if (m) return `Native ${m[1]}`;
  return raw;
}
function backupStateText(e) {
  if (!e) return '';
  const sel = String(e.selected || 'NONE');
  const word = sel === 'NONE' ? 'PRIMARY' : `BKP ${sel}`;
  return e.auto ? `${word} AUTO` : word;
}
