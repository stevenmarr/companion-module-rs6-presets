const memNum = (m) => (m ? m.id : '');
const memName = (m) => (m ? m.label || '' : '');

// 0.4.0: tiles can be swapped / moved in the app (POST /api/presets/swap). A preset number IS a tile position, so
// every per-preset variable exists for each tile 1..max(24, highest number), filled or not: a Stream Deck page
// laid out like the app's grid keeps following the TILE. After a swap the "preset 3" button shows, recalls and
// tallies whatever is now in tile 3; a tile emptied by a move shows "<n> (empty)" instead of a stale name.
const MIN_TILES = 24;
const MAX_TILES = 96;
// 0.5.0: the app's tile count (Settings › Preset tiles, 24/48/72/96; app 0.5.0+), at least 24, plus any preset
// above it. Capped at 96 + the used tiles above 96, so Companion never gets thousands of variables.
function tileCount(state) {
  const n = Number(state && state.tileCount);
  return Number.isInteger(n) && n >= MIN_TILES ? Math.min(n, MAX_TILES) : MIN_TILES;
}
function presetSlots(state) {
  const ps = (state && state.presets) || [];
  const base = tileCount(state);
  const used = ps.map((p) => Number(p.number) || 0);
  const max = Math.max(base, ...used.filter((n) => n <= MAX_TILES));
  const out = Array.from({ length: max }, (_, i) => i + 1);
  for (const n of used.filter((x) => x > max).sort((a, b) => a - b)) out.push(n); // used tiles beyond 96
  return out;
}

// ---------- app / module version check ----------
// 0.6.0 (PV Control Center): the module talks to the Control Center app 0.8.0 (API 8) for E2, PixelHue, ATEM
// and PTZ. RS6 controls keep working from API 5 (app 0.5.0) up; the other systems need API 8.
const EXPECTED_API = 8; // app 0.8.0
const MIN_API = 5; // oldest app whose RS6 API this module still speaks
// null = fine; otherwise a short warning for the log and the connection status
function versionProblem(state) {
  if (!state) return null;
  const app = state.appVersion || 'unknown';
  const api = Number(state.apiVersion);
  if (!api) return `Control Center app ${app} is older than this module expects (app 0.8.0, API ${EXPECTED_API}): update the app; tile moves, tile counts and shows need it`;
  if (api < MIN_API) return `Control Center app ${app} has API ${api}, this module expects ${EXPECTED_API}: update the app`;
  if (api < EXPECTED_API) return `Control Center app ${app} has API ${api}, this module expects ${EXPECTED_API}: RS6 controls work, E2 / PixelHue / ATEM / PTZ need app 0.8.0: update the app`;
  if (api > EXPECTED_API) return `Control Center app ${app} has API ${api}, newer than this module (API ${EXPECTED_API}): update the Companion module`;
  return null;
}
