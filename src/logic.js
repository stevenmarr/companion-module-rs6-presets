function findPreset(state, number) { return state && state.presets ? state.presets.find((p) => p.number === Number(number)) : undefined; }

// which: 'pvw' | 'pgm'. includePartial lights the button if any of the preset's destinations carry it.
function presetTally(state, number, which, includePartial = false) {
  const p = findPreset(state, number); if (!p || !p.tally) return false;
  const v = p.tally[which];
  return v === 'full' || (includePartial && v === 'partial');
}

function destSelected(state, key) {
  const k = String(key).toUpperCase();
  if (selectionKeys(state).includes(k)) return true;
  const d = findDest(state, key);
  return !!(d && d.selected);
}

// Destinations a preset was assigned in the app: its `targets` (screens plus the Master's screens),
// or the Screen destinations plus master.dests on an older state that has no targets list.
function presetTargets(p) {
  if (!p) return [];
  const raw = Array.isArray(p.targets) && p.targets.length
    ? p.targets
    : [...(p.destinations || []), ...((p.master && p.master.dests) || [])];
  const out = []; const seen = new Set();
  for (const k of raw) {
    const key = String(k).toUpperCase();
    if (!/^[SA]\d+$/.test(key) || seen.has(key)) continue;
    seen.add(key); out.push(key);
  }
  return out;
}

function selectionKeys(state) {
  const targets = state && Array.isArray(state.transitionTargets) && state.transitionTargets.length ? state.transitionTargets : null;
  const list = targets || (state && state.selection) || [];
  return list.map((k) => String(k).toUpperCase());
}

// Keys to POST to /api/selection after a recall, or null when the app already selected this preset's destinations.
// 0.5.0: apps that report transitionTargets (0.3.1+) move the selection onto the recalled preset themselves, so the
// module leaves it alone (a second POST /api/selection raced the app and could re-select screens the device does
// not have). Only older apps get the explicit selection, limited to destinations the app knows.
function selectionToApply(state, number) {
  if (state && Array.isArray(state.transitionTargets)) return null;
  const known = new Set(((state && state.destinations) || []).map((d) => String(d.key).toUpperCase()));
  const keys = presetTargets(findPreset(state, number)).filter((k) => !known.size || known.has(k));
  if (!keys.length) return null;
  const now = selectionKeys(state);
  if (now.length === keys.length && keys.every((k) => now.includes(k))) return null;
  return keys;
}

// Screens a Master memory covers, as stored on a preset (master.dests) or on the board.
// The device does not report this. Newest preset wins when two presets disagree.
// [] = the app never said which screens, so the selection must be left alone.
const destOrder = (k) => (k[0] === 'S' ? 0 : k[0] === 'A' ? 1000 : 2000) + Number(String(k).slice(1));
function masterCover(state, slot) {
  const n = Number(slot);
  const known = new Set(((state && state.destinations) || []).map((d) => String(d.key).toUpperCase()));
  const keep = (list) => {
    const out = []; const seen = new Set();
    for (const k of list || []) {
      const key = String(k).toUpperCase();
      if (!/^[SA]\d+$/.test(key) || seen.has(key)) continue;
      if (known.size && !known.has(key)) continue;
      seen.add(key); out.push(key);
    }
    return out.sort((a, b) => destOrder(a) - destOrder(b));
  };
  const hits = ((state && state.presets) || [])
    .filter((p) => p && p.master && Number(p.master.slot) === n)
    .map((p) => ({ at: String(p.updatedAt || ''), dests: keep(p.master.dests) }))
    .filter((x) => x.dests.length)
    .sort((a, b) => (a.at < b.at ? 1 : a.at > b.at ? -1 : 0));
  if (hits.length) return hits[0].dests;
  const st = state && state.staging && state.staging.master;
  if (st && Number(st.slot) === n) { const ds = keep(st.dests); if (ds.length) return ds; }
  return [];
}
// Keys to POST to /api/selection after a Master memory load, or null when there is nothing to change.
// Preset recall already moves the selection (the app does it, and selectionToApply covers older apps).
// A Master memory button does not: through app 0.9.0, POST /api/memories/load leaves the destination
// group untouched, so the module sets the screens that master was given.
function masterSelection(state, slot) {
  const keys = masterCover(state, slot);
  if (!keys.length) return null;
  const now = ((state && state.selection) || []).map((k) => String(k).toUpperCase());
  if (now.length === keys.length && keys.every((k) => now.includes(k))) return null;
  return keys;
}

