#!/usr/bin/env node
'use strict';
// Writes src/ptz-ops.js: every PTZ camera command the Control Center app knows (its lib/drivers/ptz-commands.js
// catalog, which is the bitfocus companion-module-panasonic-ptz command set plus the AW-UE150 spec additions),
// merged over all camera series. This is only the fallback for the action dropdowns: at runtime the module reads
// each camera's own catalog from the app (GET /api/sys/ptz/cameras/:id/catalog) for its options and ranges.
//
//   node tools/gen-ptz-ops.js [path to the Control Center app repo, default ../rs6-presets]
const fs = require('fs'); const path = require('path');
const app = path.resolve(process.argv[2] || path.join(__dirname, '..', '..', 'rs6-presets'));
const C = require(path.join(app, 'lib', 'drivers', 'ptz-commands.js'));
const m = new Map(); const all = [...Object.keys(C.DATA.series), 'Other'];
for (const s of all) {
  for (const o of C.catalogFor(s).ops) {
    if (!o.type) continue; // motion entries have their own actions
    const e = m.get(o.id);
    if (!e) { m.set(o.id, { id: o.id, group: o.group, label: o.label, type: o.type, ...(o.range ? { range: o.range } : {}), ...(o.options ? { options: o.options.map((x) => [x[0], x[1]]) } : {}), series: [s] }); continue; }
    e.series.push(s);
    if (o.options && e.options) { const ids = new Set(e.options.map((x) => x[0])); for (const x of o.options) if (!ids.has(x[0])) e.options.push([x[0], x[1]]); }
  }
}
const ops = [...m.values()].map((e) => ({ ...e, series: e.series.length === all.length ? 'all' : e.series }));
const out = `'use strict';\n// GENERATED by tools/gen-ptz-ops.js from the Control Center app's PTZ command catalog. Do not edit by hand.\n// series: 'all' or the camera series (companion-module-panasonic-ptz names) that have the command.\nmodule.exports = ${JSON.stringify(ops, null, 0).replace(/\},\{/g, '},\n  {')};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'ptz-ops.js'), out);
console.log(`wrote ${ops.length} PTZ commands to src/ptz-ops.js`);
